<?php

// Builds dist/agent.php: every class in src/ (bracketed namespaces), the Ed25519 verification subset of
// paragonie/sodium_compat (renamed to a private AutoWpVendor_ prefix so it can never clash with the copy
// WordPress bundles), then the global-scope entry from src/main.php. Prints the sha256.
declare(strict_types=1);

$root = dirname(__DIR__);
$src = $root . '/src';
$vendor = $root . '/vendor/paragonie/sodium_compat/src';
if (!is_dir($vendor)) {
    fwrite(STDERR, "run composer install first\n");
    exit(1);
}

// Interfaces and parents first: a class can only be declared after what it extends/implements.
$first = ['Archive/ByteSink.php', 'Archive/ByteSource.php', 'Db/Connection.php', 'Jobs/JobHandler.php'];
$files = [];
$it = new RecursiveIteratorIterator(new RecursiveDirectoryIterator($src, FilesystemIterator::SKIP_DOTS));
foreach ($it as $f) {
    $rel = substr($f->getPathname(), strlen($src) + 1);
    if (substr($rel, -4) === '.php' && $rel !== 'main.php' && !in_array($rel, $first, true)) {
        $files[] = $rel;
    }
}
sort($files, SORT_STRING);
$files = array_merge($first, $files);

$out = "<?php\n"
    . "/*\n * auto-wp agent (single-file build). GENERATED by agent-php/bin/build.php - do not edit.\n"
    . " * Source: agent-php/src. Bundles the Ed25519 subset of paragonie/sodium_compat (ISC license,\n"
    . " * (c) Paragon Initiative Enterprises) under the AutoWpVendor_ class prefix.\n */\n\n";

foreach ($files as $rel) {
    $code = (string) file_get_contents($src . '/' . $rel);
    $code = preg_replace('/^<\?php\s*/', '', $code);
    $code = preg_replace('/^declare\(strict_types=1\);\s*/m', '', (string) $code);
    if (preg_match('/^namespace\s+([A-Za-z0-9_\\\\]+);\s*$/m', (string) $code, $m) !== 1) {
        fwrite(STDERR, "no namespace in $rel\n");
        exit(1);
    }
    $code = str_replace($m[0], '', (string) $code);
    $out .= '// ---- src/' . $rel . "\nnamespace " . $m[1] . " {\n" . trim((string) $code) . "\n}\n\n";
}

$vendorFiles = [
    'Core/Util.php',
    'Core/Curve25519/Fe.php',
    'Core/Curve25519/Ge/P1p1.php',
    'Core/Curve25519/Ge/P2.php',
    'Core/Curve25519/Ge/P3.php',
    'Core/Curve25519/Ge/Precomp.php',
    'Core/Curve25519/Ge/Cached.php',
    'Core/Curve25519/H.php',
    'Core/Curve25519.php',
    'Core/Ed25519.php',
];
$out .= "// ---- paragonie/sodium_compat (subset)\nnamespace {\n"
    . "if (!class_exists('AutoWpVendor_SodiumException', false)) {\n"
    . "    class AutoWpVendor_SodiumException extends \\Exception {}\n}\n"
    . "// Minimal stand-in for ParagonIE_Sodium_Compat: verification only touches these members.\n"
    . "if (!class_exists('AutoWpVendor_ParagonIE_Sodium_Compat', false)) {\n"
    . "    class AutoWpVendor_ParagonIE_Sodium_Compat\n    {\n"
    . "        public static \$disableFallbackForUnitTests = false;\n"
    . "        public static \$fastMult = false;\n"
    . "        public static function memzero(&\$var) { \$var = null; }\n    }\n}\n";
foreach ($vendorFiles as $rel) {
    $code = (string) file_get_contents($vendor . '/' . $rel);
    $code = preg_replace('/^<\?php\s*/', '', $code);
    $code = preg_replace('/^if \(class_exists\(\'[A-Za-z0-9_]+\', false\)\) \{\s*return;\s*\}\s*/m', '', (string) $code);
    $code = preg_replace('/^if \(!class_exists\(\'[A-Za-z0-9_]+\', false\)\) \{\s*require_once[^\n]*\n\}\s*/m', '', (string) $code);
    if (strpos((string) $code, 'return;') !== false && preg_match('/^\s*return;/m', (string) $code) === 1
        && preg_match('/^return;/m', (string) $code) === 1) {
        fwrite(STDERR, "top-level return left in $rel\n");
        exit(1);
    }
    $out .= '// ' . $rel . "\n" . trim((string) $code) . "\n";
}
$out .= "}\n\n";

$main = (string) file_get_contents($src . '/main.php');
$main = preg_replace('/^<\?php\s*/', '', $main);
$out .= "// ---- entry (src/main.php)\nnamespace {\ndefine('AUTOWP_AGENT_FILE', __FILE__);\n" . trim((string) $main) . "\n}\n";

$out = str_replace(['ParagonIE_Sodium_', 'SodiumException'], ['AutoWpVendor_ParagonIE_Sodium_', 'AutoWpVendor_SodiumException'], $out);
$out = str_replace(['AutoWpVendor_AutoWpVendor_'], ['AutoWpVendor_'], $out);

foreach (['eval(', 'base64_decode(gz', 'gzinflate(base64', 'str_rot13(', 'assert('] as $bad) {
    if (stripos($out, $bad) !== false) {
        fwrite(STDERR, "forbidden construct in build: $bad\n");
        exit(1);
    }
}

$dest = $root . '/dist/agent.php';
if (in_array('--check', $argv, true)) {
    if (!is_file($dest) || file_get_contents($dest) !== $out) {
        fwrite(STDERR, "dist/agent.php is stale: run php bin/build.php\n");
        exit(1);
    }
    echo "dist/agent.php is up to date, sha256 " . hash_file('sha256', $dest) . "\n";
    exit(0);
}
@mkdir($root . '/dist', 0755, true);
file_put_contents($dest, $out);
$lint = [];
exec(escapeshellarg(PHP_BINARY) . ' -l ' . escapeshellarg($dest) . ' 2>&1', $lint, $code);
if ($code !== 0) {
    fwrite(STDERR, implode("\n", $lint) . "\n");
    exit(1);
}
echo 'dist/agent.php ' . strlen($out) . ' bytes sha256 ' . hash_file('sha256', $dest) . "\n";
