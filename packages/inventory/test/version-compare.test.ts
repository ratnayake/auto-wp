import { describe, expect, it } from 'vitest';
import { canonicalize, versionCompare } from '../src/version-compare.js';
import fixture from './fixtures/version-compare.json' with { type: 'json' };

describe('versionCompare parity with PHP version_compare()', () => {
  it('fixture was generated by a PHP 8.x CLI', () => {
    expect(fixture.phpVersion).toMatch(/^8\./);
    expect(fixture.pairs.length).toBeGreaterThanOrEqual(60);
  });

  it.each(fixture.pairs)('$a vs $b -> $expected', ({ a, b, expected }) => {
    expect(versionCompare(a, b)).toBe(expected);
  });
});

describe('canonicalize', () => {
  it.each([
    ['1.0.0-RC1', '1.0.0.RC.1'],
    ['5.3alpha2', '5.3.alpha.2'],
    ['2.5+build_7', '2.5.build.7'],
    ['1.0#', '1.0.#'],
    ['', ''],
  ])('%s -> %s', (input, expected) => {
    expect(canonicalize(input)).toBe(expected);
  });
});

describe('versionCompare', () => {
  it('orders numeric segments numerically, not lexically', () => {
    expect(versionCompare('1.10', '1.9')).toBe(1);
    expect(versionCompare('6.6.2', '6.7')).toBe(-1);
  });

  it('treats a pre-release as lower than its release', () => {
    expect(versionCompare('5.3.0-dev', '5.3.0')).toBe(-1);
    expect(versionCompare('2.0.0-rc.1', '2.0.0')).toBe(-1);
  });

  it('is antisymmetric on the fixture pairs', () => {
    for (const { a, b } of fixture.pairs) {
      expect(versionCompare(b, a) + versionCompare(a, b)).toBe(0);
    }
  });
});
